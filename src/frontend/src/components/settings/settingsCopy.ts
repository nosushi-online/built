export const SETTINGS_COPY: Record<Language, Record<SettingsKey, string>> = {
  fr,
  en,
};

export function settingsText(
  language: Language,
  key: SettingsKey,
  vars?: Record<string, string | number>,
): string {
  const template = SETTINGS_COPY[language][key] ?? SETTINGS_COPY.fr[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
