const GUEST_DICTIONARIES: Record<Language, Record<GuestTextKey, string>> = {
  fr,
  en,
};

/** Guest-screen translator, sharing the shell's active language. */
export function useGuestText() {
  const { language } = useI18n();
  return (
    key: GuestTextKey,
    vars?: Record<string, string | number>,
  ): string => {
    const template = GUEST_DICTIONARIES[language][key] ?? fr[key];
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in vars ? String(vars[name]) : match,
    );
  };
}
